import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

for (const width of [1440, 390]) test(`plain repair feedback and distinct progress/evidence files at ${width}px`, async ({ page, browserName }) => {
  await page.setViewportSize({ width, height: 900 });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('./'); await expect(page).toHaveTitle('After the Agent');
  await page.getByRole('button', { name: 'Take over the lights' }).click();
  await page.getByRole('button', { name: 'Begin takeover', exact: true }).click();
  await page.getByRole('button', { name: 'Check repair', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Repair did not hold' })).toBeVisible();
  await expect(page.locator('#result .check-total')).toContainText('future scenarios');
  await page.getByLabel('Delivery guard', { exact: true }).check();
  const receipt = page.getByRole('status', { name: 'Edit receipt', exact: true });
  await expect(receipt).toContainText('Delivery guard: Off to On');
  await expect(receipt.locator('details')).not.toHaveAttribute('open', '');
  await page.getByRole('button', { name: 'Check repair', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Repair held' })).toBeVisible();
  await expect(page.locator('#result')).toContainText('All 12 future scenarios passed');
  await expect(page.getByRole('button', { name: 'Download verification packet', exact: true })).toBeHidden();
  const progressDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save progress to a file', exact: true }).click();
  const progressRaw = await readFile((await (await progressDownload).path())!, 'utf8'), progress = JSON.parse(progressRaw);
  expect(progress.format).toBe('after-the-agent.resume');
  await page.getByText('Export and inspect evidence', { exact: true }).click();
  const evidenceDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download attempt evidence', exact: true }).click();
  const evidenceRaw = await readFile((await (await evidenceDownload).path())!, 'utf8'), evidence = JSON.parse(evidenceRaw);
  expect(evidence.attempt_id).toBe(progress.session.attempt_id);
  expect(evidence.deadline_at_ms).toBe(progress.session.deadline_at_ms);
  expect(evidence.evaluation.status).toBe('pass');
  await page.getByLabel('Restore attempt', { exact: true }).setInputFiles({ name: 'evidence.json', mimeType: 'application/json', buffer: Buffer.from(evidenceRaw) });
  await expect(page.getByRole('status').filter({ hasText: 'Attempt rejected: Use a Save progress to a file download' })).toBeVisible();
  await page.getByLabel('Restore attempt', { exact: true }).setInputFiles({ name: 'progress.json', mimeType: 'application/json', buffer: Buffer.from(progressRaw) });
  await expect(page.getByText('Attempt restored. Commands were validated and replayed. The original deadline still applies.', { exact: true })).toBeVisible();
  await page.getByRole('heading', { name: 'Repair held', exact: true }).focus();
  expect((await new AxeBuilder({ page }).analyze()).violations.filter(item => ['critical', 'serious'].includes(item.impact ?? ''))).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const output = `evidence/clarity/browser/${browserName}`; await mkdir(output, { recursive: true });
  await page.screenshot({ path: `${output}/result-${width}.png` });
  expect(errors).toEqual([]);
  await writeFile(`${output}/journey-${width}.json`, JSON.stringify({ browser: browserName, width, status: 'passed', files_distinct: true, original_deadline_preserved: true, evidence_cannot_resume: true, critical_serious_axe_violations: 0, errors, human_observation: false }, null, 2) + '\n');
});
